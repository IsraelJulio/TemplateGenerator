import { chromium } from 'file:///C:/Users/2273129/tg-t11-clean/src/web/node_modules/playwright/index.mjs';
import fs from 'node:fs'; import crypto from 'node:crypto';
const [,, name, arch, db, auth, swagger, tag] = process.argv;
const labels={simple:'Simples',clean:'Clean Architecture',none:'Nenhum',sqlite:'SQLite',postgresql:'PostgreSQL',identity:'Identity',jwt:'JWT'};
const b = await chromium.launch();
const p = await b.newPage({ viewport:{width:1280,height:1000}, acceptDownloads:true });
await p.goto('http://localhost:4200');
await p.getByLabel('Nome do projeto').fill(name);
await p.getByRole('radio',{name:new RegExp(labels[arch])}).check();
await p.locator('input[name=database][data-value='+db+']').check();
await p.locator('input[name=authentication][data-value='+auth+']').check();
const sw = p.getByLabel('Incluir no projeto');
if ((await sw.isChecked()) !== (swagger==='on')) await sw.click();
await p.screenshot({path:`evidence/${tag}-1-formulario.png`, fullPage:true});
const [dl] = await Promise.all([p.waitForEvent('download'), p.getByRole('button',{name:'Gerar projeto'}).click()]);
const out=`downloads/${tag}-${dl.suggestedFilename()}`; fs.mkdirSync('downloads',{recursive:true});
await dl.saveAs(out);
await p.waitForTimeout(1000);
await p.screenshot({path:`evidence/${tag}-2-apos-download.png`, fullPage:true});
console.log('arquivo', out, 'sha256', crypto.createHash('sha256').update(fs.readFileSync(out)).digest('hex'));
await b.close();
